def run(L, order):
    """live.py 가 부른다. order 가 글자면 새 사건을 열어 끝까지 쓰고, None 이면 받은 글에 답하거나 쓰다 만 사건을 잇는다. -> (성공, 실패 이유)"""
    t0 = time.time()
    if order is None:
        c = L.case()
        if not c:
            return False, '열린 사건이 없습니다'
        if json.loads(read(c / 'state.json') or '{}').get('finished'):
            return reply(L, c.name, t0)
        return finish(L, c.name, t0)
    L.status = '편집 중'
    people = people_of()
    out = premise_in_two(L, people, order)
    if not out:
        prompt = PREMISE.format(order=order or '(없음)', people=people, used=used(L, short=True)) + SCRIPT + SYNTAX + people_in(L, order or '')
        out = ask(L, prompt, deep=True, timeout=2400, tag='premise') or ask(L, prompt, deep=True, timeout=2400, tag='premise-again')      # 첫 화면이 여기서 뜬다. 깊게 돌리면 2~4분이 걸려 화면이 그동안 비지만, 얕게 돌리면 후보를 떠올려도 같은 결(사연, 조작 퍼즐)에만 머문다(2026-11-21 시험)
    if not out or '=== 사건' not in out:
        return False, '사건 문서를 열지 못했습니다. 새 사건 문서를 다시 누릅니다'
    case = re.sub(r'[\\/:*?"<>|\s]', '', out.split('=== 사건', 1)[1].split('\n')[0].strip(' |'))[:20] or '사건'
    while (L.root / 'plan' / case).exists():
        case += '2'
    (L.root / 'plan' / case).mkdir(parents=True)
    n, _ = apply(L, re.sub(r'^=== 사건.*$', f'=== 사건 | {case}', out, count=1, flags=re.M), case)
    state(L, case, phase='겉', turn=1, sealed=False, order=order or '')
    note(L, f'얼개와 첫 화면: 편집 {n}개', t0)
    L.current, L.opening = case, False; S.write((L.dir / 'current.txt'), case); (L.dir / 'pending_order.json').unlink(missing_ok=True)
    L.seal_check()
    return finish(L, case, t0)


def finish(L, case, t0):
    """쓰다 만 곳부터 끝까지. 어디까지 했는지는 설계 파일에 든 문단과 state.json 의 turn(1 첫 화면, 2 사건 전개까지, 3 본문 끝)으로 안다."""
    plan = L.root / 'plan' / case; world = '\n\n===== 세계 설계 =====\n' + read(L.root / 'plan' / 'truth.md')
    st = json.loads(read(plan / 'state.json') or '{}'); turn = st.get('turn', 0); side = None
    has = lambda title: bool(section(read(plan / 'truth.md'), title))
    did = lambda key: bool(json.loads(read(plan / 'state.json') or '{}').get(key))      # 끝낸 대목. 끊겼다가 이어 쓸 때 다시 쓰지 않는다
    halt = (False, '집필을 멈췄습니다. 이어 쓰기를 누르면 계속합니다')
    full = lambda: pack_plan(L, case, ('truth.md', 'known.md', 'names.md', 'timeline.md', 'facts.md'))      # 진상을 아는 쪽(기록 담당)이 받는 것

    def call(tmpl, tag, material, safe=True, kinds=('사건', '지역', '기관', '매체', '장소', '인물', '기타')):
        prompt = tmpl.format(now=stamp()) + SCRIPT + SYNTAX + doc_name(L, case) + material + pack_docs(L)
        out = ask(L, prompt, tag=tag) or ask(L, prompt, tag=tag + '-again')
        n = apply(L, out, case, safe=safe, kinds=kinds)[0] if out else 0
        note(L, f'{tag}: 편집 {n}개', t0); return out

    def spine(n):                       # 본문은 진상을 모르는 편집자가 쓴다. 알려진 것만 받는다
        part = PARTS[n].replace('큰 문단 `수사`', f'큰 문단 `{inquiry_name(L, case)}`') if n == 2 else PARTS[n]
        prompt = SPINE.format(now=stamp(), part=part) + SCRIPT + SYNTAX + '\n\n' + VOICE + known(L, case) + people_in(L, public_names(L, case)) + pack_docs(L)
        out = ask(L, prompt, timeout=480, tag=f'spine{n}') or ask(L, prompt, timeout=480, tag=f'spine{n}-again')
        k = apply(L, out, case, safe=True)[0] if out else 0
        tidy(L); note(L, f'줄기 {n}: 편집 {k}개', t0); return k

    L.status = '편집 중'
    # 1. 설계 앞 절반: 사람들과 알려질 때까지의 일. 그동안 다른 손이 지역·기관 문서를 쓴다
    if not has('무슨 일이 있었나'):
        side = threading.Thread(target=lambda: call(SIDE, 'side', ''), daemon=True); side.start()
        if not design(L, case, 1, st, world):
            return False, '사건의 속사정을 짜지 못했습니다. 이어 쓰기를 누르면 다시 합니다'
        note(L, '설계 앞 절반', t0)
    if stopped():
        return False, '집필을 멈췄습니다. 이어 쓰기를 누르면 계속합니다'
    # 2. 사건 전개를 쓰기 시작한다. 그동안 뒤에서 설계 뒤 절반을 짓고, 따지고, 지적된 곳을 고치고, 봉한다
    first, wrote = None, []
    if turn < 2 and not did('wrote1'):
        if side:
            side.join()
        first = threading.Thread(target=lambda: wrote.append(spine(1)) or (wrote[-1] and (state(L, case, wrote1=True), shots(L, case, '사건 전개'))), daemon=True); first.start()
    if not has('수사는 왜 못 풀었나'):
        if not design(L, case, 2, st, world):
            first and first.join()
            return False, '사건의 뒤 절반을 짜지 못했습니다. 이어 쓰기를 누르면 다시 합니다'
        note(L, '설계 뒤 절반', t0)
    if stopped():
        first and first.join()
        return halt
    if not st.get('sealed'):
        if not mend(L, case, t0):
            first and first.join()
            return False, '설계를 따져 보지 못해 봉인하지 않았습니다. 이어 쓰기를 누르면 다시 따집니다'
        state(L, case, sealed=True); L.seal_check(); jot(L, case); note(L, '봉인', t0)
        L.fill_images()                 # 해설 그림, 그리고 앞서 그리다 남은 사진
        threading.Thread(target=lambda: solution(L, case, t0), daemon=True).start()
    if first:
        first.join()
        if not wrote or not wrote[0]:
            return False, '사건 전개를 쓰지 못했습니다. 이어 쓰기를 누르면 다시 합니다'
        place_images(L, case)
    if turn < 2:
        state(L, case, phase='파기', turn=2)
    if stopped():
        return False, '집필을 멈췄습니다. 이어 쓰기를 누르면 계속합니다'
    # 3. 수사를 쓰고, 그다음 의문점·이후·여담과 토론을 쓴다. 그동안 기록 담당이 링크로 이어질 문서와 장부를 쓴다
    shot2 = None
    if turn < 3:
        def links():
            truth = public_table(L, case)      # 진상은 건네지 않는다. 표와 공개된 것만 받으면, 표에 없는 말을 덧붙일 수 없다
            call(LINKS, 'links', truth)
            miss = links_missing(L, case)
            if miss:                    # 이미 있는 문서를 새로 열려다 버려졌거나 말이 빠졌다. 그 말이 없으면 이 사건의 단서 하나가 사라진다
                call(LINKS, 'links-again', truth + '\n\n## 아직 빠진 것\n\n아래 문서에 아래 말이 아직 없다. 그 문서에 `--- 덧붙임` 으로 그 말이 든 문장을 넣는다. 이것만 한다.\n' + '\n'.join(f'- {d}: {w}' for d, w in miss), )
            mark_search(L, case)
        def around():                   # 링크가 걸린 둘레 문서. 본문 옆에서 같이 쓰므로 본문이 끝나는 때는 늦어지지 않는다
            names = unwritten(L, case)[:8]
            if not names:
                return
            # 편집자는 그 대상에 관해 아는 것이 없어서 어느 대상에나 붙는 말로 채운다. 세계를 아는 작가가 대상마다 재료를 먼저 낸다(알려진 것만)
            ask_world = lambda tag: ask(L, WORLD.format(now=stamp(), names='\n'.join(f'- {n}' for n in names)) + '\n===== 설계 =====' + pack_plan(L, case, ('truth.md', 'known.md', 'names.md')) + shelf_of(L), tag=tag, need='## ')
            mat = (ask_world('world') or ask_world('world-again') or '').replace('\r', '')

            for real, shown in re.findall(r'^- ([^:\n→]+?)[ \t]*→[ \t]*([^:,\n]+)', read(plan / 'names.md'), re.M):      # 재료에 가린 실명이 섞였으면 표기로 바꾼다
                if len(real.strip()) >= 2:
                    mat = mat.replace(real.strip(), shown.strip())
            truth = read(plan / 'truth.md'); title = (re.search(r'^## 사건 문서 이름[ \t]*\n+(.+)$', truth, re.M) or ['', case])[1].strip()
            intro = section(split_doc(read(L.root / 'docs' / f'{title}.md'))[1], '개요').strip()
            about = f'[[{title}]] (' + section(truth, '때와 곳').strip() + ')\n' + intro          # 편집자가 사건에 관해 받는 것은 이것뿐이다

            def one(n, k):
                sec = (re.search(r'^## ' + re.escape(n) + r'[ \t]*\n(.*?)(?=^## |\Z)', mat, re.M | re.S) or ['', ''])[1].strip()
                if re.fullmatch(r'-?\s*문서 없음[.。]?', sec):
                    unlink(L, n); return      # 세상이 이 사건으로만 아는 대상이다. 문서를 만들지 않고 링크를 글자로 푼다
                prompt = DOC.format(now=stamp(), name=n, material=sec or '(없음)', case=about) + SCRIPT + SYNTAX + shelf_of(L)
                apply(L, ask(L, prompt, tag=f'doc{k}') or ask(L, prompt, tag=f'doc{k}-again') or '', case, safe=True)      # 호출이 실패하면 그 문서는 빨간 링크로 남는다. 한 번 더 부른다
            together(*[(lambda n=n, k=k: one(n, k)) for k, n in enumerate(names, 1)])
            note(L, f'둘레 문서: {len(names)}개 가운데 {sum((L.root / "docs" / f"{n}.md").is_file() for n in names)}개', t0)
        bg = threading.Thread(target=lambda: together(links, lambda: call(LEDGER, 'ledger', full() + world), around), daemon=True); bg.start()
        if not did('wrote2'):
            if not spine(2):
                bg.join()
                return False, '수사를 쓰지 못했습니다. 이어 쓰기를 누르면 다시 합니다'
            state(L, case, wrote2=True)
            shot2 = threading.Thread(target=lambda: shots(L, case, inquiry_name(L, case)), daemon=True); shot2.start()
        place_images(L, case)
        if stopped():
            bg.join()
            return halt
        if not did('wrote3'):
            done3 = []
            together(lambda: done3.append(spine(3)), lambda: call(TALK, 'talk', known(L, case)))
            if not (done3 and done3[0]):          # 못 썼으면 쓴 것으로 적지 않는다. 이어 쓰기가 다시 쓴다
                bg.join(); shot2 and shot2.join()
                return False, '의문점과 이후를 쓰지 못했습니다. 이어 쓰기를 누르면 다시 합니다'
            state(L, case, wrote3=True)
        bg.join(); shot2 and shot2.join(); place_images(L, case, True)
        _, lack = unmentioned(L, case)          # 이미 있던 문서는 새로 쓰이지 않아서, 이 사건이 거기에 적히지 않는다
        if lack:
            out = ask(L, MENTION.format(now=stamp(), names='\n'.join(f'- {n}' for n in lack)) + SCRIPT + SYNTAX + doc_name(L, case) + known(L, case)
                      + '\n\n===== 덧붙일 문서들의 지금 글 =====\n' + '\n\n'.join(f'### {n}\n' + split_doc(read(L.root / 'docs' / f'{n}.md'))[1].strip() for n in lack), tag='mention') or ''
            note(L, f'이미 있는 문서에 사건 적기: {len(lack)}개 가운데 편집 {apply(L, out, case, safe=True)[0] if out else 0}개', t0)
        tidy(L)
        # 편집자들은 어느 사실이 단서인지 모른다. 사다리의 단이 문서에 다 들어갔는지는 기록 담당이 확인하고, 빠진 사실은 편집자가 넣는다
        call(PIECES, 'pieces', full())
        if not (plan / 'pieces.md').is_file():      # 형식이 어긋나 표가 안 생겼다. 이 표가 없으면 검사와 채점이 서지 않는다
            call(PIECES, 'pieces-retry', full())
        if not (plan / 'pieces.md').is_file():      # 그래도 없으면 여기서 멈춘다. 다음 차례로 넘기면 이어 쓰기가 이 단계를 건너뛰고, 고치는 호출이 엉뚱한 꼴의 표를 지어 오류가 늘었다
            return False, '조각 표를 쓰지 못했습니다. 이어 쓰기를 누르면 다시 합니다'
        miss = rungs_missing(L, case)
        if miss:
            out = ask(L, ADD.format(facts='\n'.join(f'- {m}' for m in miss)) + SCRIPT + SYNTAX + '\n\n' + VOICE + known(L, case) + pack_docs(L), tag='add')
            note(L, f'빠진 사실 {len(miss)}개: 편집 {apply(L, out, case, safe=True)[0] if out else 0}개', t0)
            call(PIECES, 'pieces-again', full())
        state(L, case, phase='깊은 곳', turn=3)
    if stopped():
        return False, '집필을 멈췄습니다. 이어 쓰기를 누르면 계속합니다'
    # 4. 마감: 검사는 서버가 돌리고, 오류가 있을 때만 고치는 호출을 한다
    L.status = '편집 중'; LV = sys.modules['__main__']
    scrub_docs(L, case)                                   # 이름 목록 뒤에 쓰인 문서(단서를 둔 구술자료 같은)에도 실명이 들어간다. 단서 문장이라 고치는 호출은 못 건드려 사건이 멈췄다
    for attempt in range(4):                              # 고치는 호출은 세 번까지. 마지막 고침 뒤에도 한 번 더 검사해야 남은 오류 수가 맞다
        _, res = LV.tool(L.root, sys.executable, 'tools/check.py')
        errors = list(dict.fromkeys(re.sub(r'@r\d+:', ' (옛 판):', l) for l in res.splitlines() if l.startswith('오류 |')))
        errors = LV.F.own_errors(errors, L.root, plan)      # 다른 사건의 오류는 이 사건이 고칠 일이 아니다
        note(L, f'마감 검사: 오류 {len(errors)}개', t0)
        red = {m for l in errors for m in re.findall(r'\[\[(.+?)\]\] 문서가 없습니다', l)}
        if red:                                           # 없는 문서로 가는 링크는 서버가 푼다. 에이전트를 부를 일이 아니다
            import difflib
            title = case_title(L, case)                   # 이 사건을 다른 이름으로 부른 링크는 벗기지 않고 사건 문서로 고쳐 건다
            alias = {n for n in red if title and n.endswith('사건') and (difflib.SequenceMatcher(None, n, title).ratio() >= 0.5 or len(set(n.split()) & set(title.split())) >= 2)}
            have = [p.stem for p in (L.root / 'docs').glob('*.md')]
            for n in [n for n in red if n not in alias]:      # 같은 곳을 다르게 부른 링크(OO면 ↔ OO도 OO군 OO면)는 벗기지 않고 있는 문서로 건다
                same = next((h for h in have if len(min(h, n, key=len)) >= 2 and (h.endswith(' ' + n) or n.endswith(' ' + h))), '')
                if same:
                    relink_to(L, n, same); red.discard(n)
            for p in list((L.root / 'docs').glob('*.md')) + list((L.root / 'history').glob('*/*.md')):
                t = old = p.read_text(encoding='utf-8-sig')
                for name in red:
                    t = re.sub(r'\[\[' + re.escape(name) + r'(?:\|(.+?))?\]\]', lambda m: f'[[{title}]]' if name in alias else (m[1] or name), t)
                if t != old:
                    S.write(p, t)
            errors = [l for l in errors if '문서가 없습니다' not in l]
        lone = {m[1] for l in errors if (m := re.match(r'오류 \| (.+?): 시작 문서에서 링크로 갈 수 없습니다', l))}
        if lone and link_lone(L, lone, case):              # 이어지지 않은 문서는 그 이름이 글자로 나오는 곳에 서버가 링크를 건다
            continue
        if any(f'조각 {case}/' in l and '의 본문에' in l for l in errors) and align_pieces(L, case):
            continue
        if not errors or attempt == 3:
            break
        past = ''
        if any('(옛 판)' in l for l in errors):      # 옛 판에만 있고 지금 문서에는 없는 문장들을 같이 보여 준다
            now_text = all_docs(L); lines = []
            for h in sorted((L.root / 'history').glob('*/*.md')):
                for sent in re.findall(r'[^.\n]+\.', h.read_text(encoding='utf-8')):
                    if sent.strip() not in now_text and sent.strip() not in lines:
                        lines.append(sent.strip())
            past = '\n\n===== 옛 판에 있던 문장 (지금 문서에는 없다) =====\n' + '\n'.join(lines[-300:])
        out = ask(L, FIX.format(errors='\n'.join(errors)) + SCRIPT + SYNTAX + pack_plan(L, case) + pack_docs(L) + past, tag='fix')
        if out:
            apply(L, out, case, history=True)      # 검사 오류(가린 이름이 옛 판에 새는 것 같은)는 옛 판까지 고친다. 세상이 바뀐 사실은 옛 판에 그대로 둔다
    align_pieces(L, case)       # 마지막 고침이 문서 문장을 바꿨으면 조각 표를 한 번 더 맞춘다. 마지막 차례 뒤에는 맞출 기회가 없어 오류 하나가 남았다(2026-11-20)
    # 달성 점검표. 버전 24의 집필 완료 판정(caseflow.completion)이 이 표와 마감 검사를 함께 본다
    _, res = LV.tool(L.root, sys.executable, 'tools/check.py')      # 고친 뒤의 실제 상태로 적는다. 오류가 남았는데 완료로 적지 않는다
    left = LV.F.own_errors([l for l in res.splitlines() if l.startswith('오류 |')], L.root, plan)
    S.write(plan / 'next.md', '# 달성 점검표\n\n- [x] 진상 확정\n' + f'- [{" " if left else "x"}] 마감 검사\n')
    if left:
        state(L, case, finished=False); note(L, f'마감 검사: 오류 {len(left)}개가 남음', t0)
        return False, f'마감 검사 오류 {len(left)}개가 남았습니다. 이어 쓰기를 누르면 다시 고칩니다'
    state(L, case, phase='마무리', finished=True); note(L, '끝', t0)
    return True, ''


def hint(L):
    """막혔을 때 새 소식을 위키에 올린다. 세 번까지, 갈수록 진상에 가까운 것을 내놓는다. -> (성공, 실패 이유)"""
    t0 = time.time(); c = L.case()
    if not c:
        return False, '열린 사건이 없습니다'
    case = c.name; st = json.loads(read(c / 'state.json') or '{}'); level = st.get('hints', 0) + 1
    if level > 3:
        return False, '이 사건에서 더 나올 소식은 없습니다'
    last = L.verdict() or {}
    weak = [f'- {r["label"]}: {r["status"]}' for r in last.get('checks', []) if r.get('status') != '일치']
    stuck = ('마지막으로 낸 추리에서 아래 항목이 맞지 않았다. 이 항목에 닿는 데 도움이 되는 것을 고른다.\n' + '\n'.join(weak)) if weak else '아직 낸 추리가 없다. 세간의 통설에서 벗어나는 데 도움이 되는 것을 고른다.'
    name = (re.search(r'^## 사건 문서 이름\s*\n+(.+)$', read(c / 'truth.md'), re.M) or ['', ''])[1].strip()
    task = {1: f'`=== 문서` 블록 하나, `--- 토론` 이다. 사건 문서({name})의 토론에 새 주제를 연다. 편집자 둘이나 셋이, 이미 문서에 있는데 다들 그냥 지나친 사실 하나를 두고 말을 주고받는다. 새 사실은 내놓지 않는다. 그 사실이 왜 걸리는지까지만 말하고 결론은 내지 않는다.',
            2: f'`=== 문서` 블록 하나, `--- 덧붙임 | 이후` 다. 사건 문서({name})의 이후 문단에 소제목(`### `)을 달고, 뒤늦게 알려진 사실 하나를 쓴다. 지금 사람들이 믿는 설명으로는 설명되지 않는 사실이어야 한다. 누가 어떻게 알렸는지도 쓴다. 200~350자.',
            3: (f'`=== 문서` 블록 둘. 첫째는 `--- 새문서` 로, 이 사건을 다시 다룬 시사 프로그램의 문서를 연다(`type: 매체`, 프로그램 이름은 지어낸다. {ORGNAME} 이미 그런 문서가 있으면 `--- 덧붙임` 으로 그 문서에 이 사건을 다룬 회차를 더한다). '
                f'제작진이 한 재연이나 실험, 새로 만난 사람의 말을 쓴다. 핵심 결론 하나를 거의 가리키는 데까지 간다. 300~500자. 둘째는 `--- 덧붙임 | 이후` 로, 사건 문서({name})에 그 방송이 있었다는 것을 한두 문장으로 쓰고 그 문서로 링크한다.')}[level]
    L.status = '편집 중'
    prompt = HINT.format(now=stamp(), level=level, stuck=stuck, task=task) + SCRIPT + SYNTAX + pack_plan(L, case) + pack_docs(L)
    out = ask(L, prompt, tag=f'hint{level}') or ask(L, prompt, tag=f'hint{level}-again')
    n = apply(L, out, case, safe=True)[0] if out else 0
    note(L, f'소식 {level}: 편집 {n}개', t0)
    if not n:
        return False, '새 소식을 올리지 못했습니다. 다시 누릅니다'
    state(L, case, hints=level)
    return True, ''


def reply(L, case, t0):
    inbox = L.dir / 'inbox.jsonl'
    items = '\n'.join(l for l in read(inbox).splitlines() if '"text": ""' not in l and l.strip())      # 빈 글은 버린다
    if not items:
        return True, ''
    L.status = '편집 중'
    out = ask(L, REPLY.format(now=time.strftime('%Y-%m-%d %H:%M'), inbox=items) + SCRIPT + SYNTAX + pack_plan(L, case) + pack_docs(L), tag='reply')
    if not out:
        return False, '토론에 답하지 못했습니다'
    S.write(inbox, ''); n, _ = apply(L, out, case); note(L, f'토론 답: 편집 {n}개', t0)
    return True, ''
