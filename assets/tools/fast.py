def known(L, case):
    """진상을 모르는 편집자들이 받는 것. 알려진 것과 부르는 이름뿐이다. 진상 파일과 실명은 가지 않는다."""
    return '\n\n===== 알려진 것 =====\n' + read(L.root / 'plan' / case / 'known.md') + '\n\n===== 부르는 이름 =====\n' + public_names(L, case)


def merge_design(L, case, out, frozen=(), loose=()):
    """작가가 쓴 설계를 받아 넣는다. truth.md 와 known.md 는 문단 단위로 합친다(같은 제목은 바뀌고 새 제목은 붙는다).
    알맹이는 얼개에서 정한 그대로 되돌리고, frozen 에 든 known.md 문단(이미 문서로 쓰인 것)은 바꾸지 않는다. -> 바뀐 문단 수"""
    plan = L.root / 'plan' / case; core = section(read(plan / 'truth.md'), '알맹이'); n = 0
    for line in loose:                 # 알맹이 가운데 다시 지어도 되는 줄. 무슨 일이 있었나는 여기에 들지 않는다
        got = re.findall(r'^(?:[-*][ \t]*)?' + re.escape(line) + r':[ \t]*(\S.*)$', out, re.M)      # 앞에 '- '를 붙여 쓴 줄도 같은 줄이다. 못 알아보면 고친 것이 버려졌다
        fixed = re.sub(r'^([-*][ \t]*)?' + re.escape(line) + r':.*$', lambda m: (m[1] or '') + f'{line}: ' + got[-1].strip(), core, flags=re.M) if got and core else core
        if fixed != core:
            S.write((plan / 'truth.md'), read(plan / 'truth.md').replace(core, fixed)); core = fixed; n += 1
    for name in ('truth.md', 'known.md'):
        m = re.search(r'^=== [^|\n]*\|[ \t]*(?:[^|\n]*[\\/])?' + re.escape(name) + r'[ \t]*\n(.*?)(?=^=== |\Z)', out, re.M | re.S)
        if not m:
            continue
        t = read(plan / name).replace('\r\n', '\n'); block = m[1]
        locked = {'알맹이'} | (set(frozen) if name == 'known.md' else set())
        pair = r'^<<<[ \t]*\n(.*?)\n>>>[ \t]*\n?(.*?)(?=\n<<<|\n## |\Z)'
        for old, new in re.findall(pair, block, re.M | re.S):       # 줄 단위 고침. 잠긴 문단에 있는 줄은 바꾸지 않는다
            old, new = old.strip('\n'), new.strip('\n')
            for sec in re.finditer(r'^## (.+?)[ \t]*\n.*?(?=^## |\Z)', t, re.M | re.S):
                k = sec[0].find(old) if old.strip() and sec[1].strip() not in locked else -1
                if k >= 0:
                    t = t[:sec.start() + k] + new + t[sec.start() + k + len(old):]; n += 1; break
        block = re.sub(pair, '', block, flags=re.M | re.S)
        for sec in re.finditer(r'^## (.+?)[ \t]*\n.*?(?=^## |\Z)', block, re.M | re.S):
            title = sec[1].strip()
            if title == '알맹이' or (name == 'known.md' and title in frozen):
                continue
            old = re.search(SEC % re.escape(title), t, re.M | re.S); text = sec[0].rstrip('\n') + '\n\n'
            t = t[:old.start()] + text + t[old.end():] if old else t.rstrip('\n') + ('\n\n' if t.strip() else '') + text
            n += 1
        S.write((plan / name), t); out = out[:m.start()] + out[m.end():]
    if core and not section(read(plan / 'truth.md'), '알맹이'):
        S.write((plan / 'truth.md'), core.rstrip('\n') + '\n\n' + read(plan / 'truth.md').lstrip('\n'))
    if frozen:                                            # 고쳐 짓기에서는 이름 목록을 받지 않는다. 문서가 이미 그 이름으로 쓰이고 있다
        out = re.sub(r'^=== [^|\n]*\|[ \t]*(?:[^|\n]*[\\/])?names\.md[ \t]*\n.*?(?=^=== |\Z)', '', out, flags=re.M | re.S)
    apply(L, out, case)                                   # 이름 목록은 파일째로 온다
    # 실명이 알려진 것에 섞였으면 위키 표기로 바꾼다. 편집자들은 실명을 몰라야 한다
    k = read(plan / 'known.md'); new = k
    for real, shown in re.findall(r'^- ([^:\n→]+?)[ \t]*→[ \t]*([^:,\n]+)', read(plan / 'names.md'), re.M):
        if len(real.strip()) >= 2:
            new = new.replace(real.strip(), shown.strip())
    if new != k:
        S.write((plan / 'known.md'), new)
    scrub_docs(L, case)
    # 사진 주문서의 글자는 사진에 그대로 찍혀 공개된다. 실명이 들어 있으면 가린다
    im = read(plan / 'images.md'); masked = im
    for real, _ in re.findall(r'^- ([^:\n→]+?)[ \t]*→[ \t]*([^:,\n]+)', read(plan / 'names.md'), re.M):
        if len(real.strip()) >= 2:
            masked = masked.replace(real.strip(), '(가려진 이름)')
    # 사진은 모든 사건이 한 폴더(docs/img)에 파일 이름으로 들어간다. 사건마다 고유한 머리를 붙여야 이름이 겹쳐 남의 사진이 뜨지 않는다
    tag = hashlib.md5(case.encode('utf-8')).hexdigest()[:6] + '-'
    masked = re.sub(r'^(\|[ 	]*)(?!' + tag + r')([\w.-]+\.(?:png|jpg|jpeg|webp))(?=[ 	]*\|)', lambda m: m[1] + tag + m[2], masked, flags=re.M)
    if masked != im:
        S.write((plan / 'images.md'), masked)
    return n


def scrub_docs(L, case):
    """이름 목록이 생기면, 그 전에 쓰인 문서와 옛 판에 실명이 남아 있는지 보고 위키 표기로 바꾼다.
    얼개 단계에는 이름 목록이 없어서 첫 화면에 실명이 섞일 수 있다. 실명은 한 번이라도 화면에 나가면 안 된다."""
    pairs = []
    for real, shown in re.findall(r'^- ([^:\n→]+?)[ \t]*→[ \t]*([^:\n]+)', read(L.root / 'plan' / case / 'names.md'), re.M):
        real = real.strip(); marks = [x.strip() for x in shown.split(',') if x.strip()]
        if len(real) >= 2 and marks:
            pairs.append((real, marks[0], marks[-1]))
    if not pairs:
        return
    files = [p for p in (L.root / 'docs').glob('*.md') if p.stem != '대문'] + list((L.root / 'history').glob('*/*.md')) + [L.root / 'plan' / case / 'pieces.md']      # 조각 표의 문구도 문서 문장을 그대로 옮긴 것이다
    files = [p for p in files if p.is_file()]
    with LOCK:
        for p in files:
            t = old = p.read_text(encoding='utf-8-sig')
            for real, first, call in pairs:
                open_end = (ord(first[-1]) - 0xAC00) % 28 == 0 if '가' <= first[-1] <= '힣' else False      # 표기가 받침 없이 끝나면 뒤의 조사를 맞춘다
                if open_end:
                    t = re.sub(re.escape(real) + r'([’\'”"]?)이(라는|라고|었|다)', lambda m: first + m[1] + {'었': '였'}.get(m[2], m[2]), t)
                for closed, opened in (('은', '는'), ('이', '가'), ('을', '를'), ('과', '와')):
                    t = t.replace(real + closed, first + (opened if open_end else closed)).replace(real + opened, first + (opened if open_end else closed))
                fix = {'은': '는', '이': '가', '을': '를', '과': '와'} if open_end else {'는': '은', '가': '이', '를': '을', '와': '과'}
                t = re.sub(re.escape(real) + r'(\([^)\n]*\)|[’\'”"])(은|는|이|가|을|를|과|와)(?![가-힣])', lambda m: first + m[1] + fix.get(m[2], m[2]), t)
                t = t.replace(real, first).replace(first + ' ' + first, first)      # "남기환의 딸 남정희"처럼 표기와 같은 말 뒤에 실명이 있었으면 표기가 겹친다
                if len(real) == 3:          # 성을 뗀 이름만 부른 곳. 뒤에 조사가 붙은 것만 바꾼다(같은 글자의 다른 낱말을 건드리지 않게)
                    fit = {'은': '는', '이': '가', '을': '를', '과': '와'} if (ord(call[-1]) - 0xAC00) % 28 == 0 else {'는': '은', '가': '이', '를': '을', '와': '과'}
                    t = re.sub(real[1:] + r'(은|는|이|가|을|를|의|에게|과|와|도|만|에)(?![가-힣])', lambda m: call + fit.get(m[1], m[1]), t)
            if t != old:
                S.write(p, t)
    tick(L)


def people_in(L, text):
    """글에 이름이 나오는 사람 가운데 이미 위키에 인물 문서가 있는 사람의 문서를 앞에 떼어 둔다.
    문서는 통째로도 넘기지만 수백 개 사이에 묻혀 작가가 못 본다(같은 사람의 나이가 사건마다 다르게 실렸다)."""
    out = []
    for p in sorted((L.root / 'docs').glob('*.md')):
        if len(p.stem) >= 2 and p.stem in text and re.search(r'^type:[ \t]*인물', read(p), re.M):
            out.append(f'\n\n===== docs/{p.name} =====\n{read(p)}')
    if not out:
        return ''
    return ('\n\n===== 이미 위키에 있는 사람 =====\n이 사건에 나오는 사람 가운데 아래 사람은 이미 이 위키에 문서가 있다. '
            '그 문서에 적힌 것(태어난 해, 하는 일, 사는 곳, 겪은 일)은 이 위키의 사실이다.' + ''.join(out))


def names_used(L, case):
    """이 위키의 다른 사건에 이미 나온 이름. 사건마다 따로 지으니 모델이 즐겨 쓰는 이름이 되풀이됐다(한 위키에 '태수' 다섯, '중앙'·'대성' 상호 일곱. 2026-11-23).
    목록을 주니 겹침이 열여덟에서 하나로 줄었다."""
    seen = sorted({m[1].strip() for p in (L.root / 'plan').glob('*/names.md') if p.parent.name != case
                   for l in read(p).splitlines() if (m := re.match(r'^- ([^:→\n]+?)\s*(?:→|:)', l))})
    if not seen:
        return ''
    return ('\n\n===== 이 위키에 이미 나온 이름 =====\n이 위키의 다른 사건에 이미 나온 이름들이다. 새로 짓는 사람 이름(성을 뺀 이름도)과 가게·회사 이름(업종 앞에 붙은 말도)은 이것들과 겹치지 않게 짓는다. '
            '이미 나온 사람이나 가게를 이 사건에 다시 쓰는 것이면 그 이름을 그대로 쓴다. 지명, 실제 있었던 일, 실존 인물은 그대로 쓴다.\n' + ', '.join(seen))


def design(L, case, half, st, world):
    """작가가 사건의 절반을 짓는다. 1: 사람들과 알려질 때까지의 일, 2: 수사와 그 뒤, 사다리. 진상(truth.md)과 알려진 것(known.md) 두 벌로 온다."""
    tmpl, need = (STORY1, ('## 무슨 일이 있었나', '## 알려진 일')) if half == 1 else (STORY2, ('## 수사는 왜 못 풀었나', '## 사다리', '## 수사\n'))
    prompt = (tmpl.format(order=st.get('order') or '(없음)', people=people_of(), used=used(L), shelf=shelf(L))
              + SCRIPT + world + pack_plan(L, case, ('truth.md', 'known.md', 'names.md')) + screen(L, case)
              + people_in(L, (st.get('order') or '') + read(L.root / 'plan' / case / 'truth.md') + read(L.root / 'plan' / case / 'names.md')) + pack_docs(L)
              + (names_used(L, case) if half == 1 else ''))
    for tag in (f'story{half}', f'story{half}-again'):
        out = (ask(L, prompt, timeout=600, tag=tag) or '').replace('\r\n', '\n')
        named = [r.strip() for r, shown in re.findall(r'^- ([^:\n→]+?)[ \t]*→[ \t]*([^:\n]+)', out, re.M) if len(r.strip()) >= 2 and r.strip() in shown]
        # 가린 표기의 성 자리에 이름의 첫 글자를 적는 일이 있다(최유정 → 유 모 씨). 문서에는 표기만 나가므로 식구의 성이 달라 보인다. 실명의 성으로 바로잡는다
        out = re.sub(r'^(- ([가-힣])([가-힣])[가-힣]{0,2}[ \t]*→[ \t]*)([^:\n]+)',
                     lambda m: m[1] + re.sub(r'(?<![가-힣])' + m[3] + r'(?= (?:모 )?(?:씨|양|군))', m[2], m[4]) if m[2] != m[3] else m[0], out, flags=re.M)
        for r in named:                # 표기에 실명을 그대로 적었다. 작가가 그 이름을 싣기로 한 것이다. 가리는 이름이 아니므로 화살표 없는 줄로 둔다
            out = re.sub(r'^- ' + re.escape(r) + r'[ \t]*→[^:\n]+:', f'- {r} :', out, flags=re.M)
        if all(n in out for n in need) and 'known.md' in out:
            merge_design(L, case, out, frozen=() if half == 1 else ('사람들', '알려진 일'), loose=('왜', '왜 드러나지 않았나') if half == 1 else ())
            return True
    return False


def public_table(L, case):
    """숨은 문서를 쓰는 쪽이 받는 것: 사건 문서 이름, 세상이 처음 본 것, 다른 문서에 놓을 것 표. 진상은 없다."""
    t = read(L.root / 'plan' / case / 'truth.md')
    return ('\n\n===== 사건 문서 이름 =====\n' + section(t, '사건 문서 이름').strip()
            + '\n\n===== 세상이 처음 본 것 =====\n' + section(t, '알려진 순간').strip()
            + '\n\n===== 다른 문서에 놓을 것 =====\n' + section(t, '다른 문서에 놓을 것').strip())


def blind(L, case):
    """진상을 모르는 시험 독자가 실제로 풀어 본다. -> 따져 보기에 붙일 글.
    숨은 문서 한 줄마다 따로(그 한 줄과 세상이 처음 본 것만으로 답이 나오면 너무 쉽다), 그리고 공개 재료 전부로 한 번(답 근처에도 못 가면 단서가 모자란다)."""
    t = read(L.root / 'plan' / case / 'truth.md'); start = section(t, '알려진 순간').strip()
    rows = []
    for l in section(t, '다른 문서에 놓을 것').splitlines():
        c = [x.strip() for x in l.strip().strip('|').split('|')]
        if l.strip().startswith('|') and len(c) >= 4 and c[0] and c[0] != '문서 이름' and not re.fullmatch(r'[-: ]+', c[0]) and c[3]:
            rows.append((c[0], c[3]))
    jobs = [(f'[{d}] 한 줄만', start + f'\n\n(위키의 다른 문서 "{d}"에 이런 문장이 있다)\n{q}') for d, q in rows]
    jobs.append(('공개 재료 전부', read(L.root / 'plan' / case / 'known.md') + '\n\n(위키의 다른 문서들에 흩어진 문장)\n' + '\n'.join(f'- [{d}] {q}' for d, q in rows)))
    got = {}
    together(*[(lambda k=k, m=m: got.__setitem__(k, ask(L, READER + '\n\n===== 읽은 것 =====\n' + m, tag='blind', need='무슨 일이었나') or '(답 없음)')) for k, m in jobs])
    return '\n\n===== 시험 독자 (진상을 모른다) =====\n' + '\n\n'.join(f'### {k}\n{got.get(k, "")}' for k, _ in jobs)


def mend(L, case, t0):
    """지은 설계를 다른 호출이 담당 형사, 편집자, 독자의 눈으로 따지고, 지적이 있으면 작가가 지적된 문단만 고쳐 쓴다."""
    files = ('truth.md', 'known.md', 'names.md')
    trial = blind(L, case)
    note(L, '시험 독자', t0)
    prompt = CRITIC + pack_plan(L, case, files) + screen(L, case) + trial
    verdict = (ask(L, prompt, deep=True, timeout=300, tag='critic', need='판정')
               or ask(L, prompt, deep=True, timeout=300, tag='critic-again', need='판정') or '')
    head = verdict.split('\n', 1)[0]
    if '통과' not in head and '고칠 것' not in head:      # 답이 없거나 판정을 못 읽었다. 통과로 치면 따지지 않은 설계가 봉인된다
        note(L, '따져 보기: 실패', t0)
        return False
    fix = '고칠 것' in head
    note(L, '따져 보기: ' + ('고칠 것' if fix else '통과'), t0)
    if not fix:
        return True
    out = ask(L, MEND + SCRIPT + pack_plan(L, case, files) + screen(L, case) + '\n\n===== 따져 본 결과 =====\n' + verdict, timeout=420, tag='mend') or ''
    note(L, f'고쳐 짓기: {merge_design(L, case, out.replace(chr(13), ""), frozen=("사람들", "알려진 일"), loose=("왜 드러나지 않았나",))}곳 (출력 {len(out)}자)', t0)
    return True


def unmentioned(L, case):
    """사건 문서가 가리키는 문서 가운데 이 사건을 적지 않은 것. 단서를 두는 지식 문서는 뺀다(그런 문서에는 사건을 적지 않는다)."""
    truth = read(L.root / 'plan' / case / 'truth.md'); name = (re.search(r'^## 사건 문서 이름[ \t]*\n+(.+)$', truth, re.M) or ['', ''])[1].strip()
    doc = L.root / 'docs' / f'{name}.md'
    if not name or not doc.is_file():
        return name, []
    part = (re.search(r'^## 다른 문서에 놓을 것.*?(?=^## |\Z)', truth, re.M | re.S) or [''])[0]
    lore = {c[0] for c in ([x.strip() for x in l.strip().strip('|').split('|')] for l in part.splitlines() if l.strip().startswith('|')) if len(c) > 1 and '지식' in c[1]}
    out = []
    for n in re.findall(r'\[\[([^\]|#]+)', split_doc(read(doc))[1]):
        n = n.strip(); t = read(L.root / 'docs' / f'{n}.md')
        if n and n != name and n not in out and n not in lore and t and f'[[{name}' not in t and not re.search(r'^type:[ \t]*사건', t, re.M):
            out.append(n)
    return name, out[:10]


def unwritten(L, case):
    """알려진 것과 지금까지의 문서에 링크가 걸렸는데 아직 문서가 없는 이름들. 단서를 두려고 따로 여는 문서(다른 문서에 놓을 것)는 뺀다."""
    plan = L.root / 'plan' / case
    text = read(plan / 'known.md') + ''.join(read(p) for p in (L.root / 'docs').glob('*.md'))
    skip = {c for c, _ in links_missing(L, case)} | {'대문'}
    names, have = [], [p.stem for p in (L.root / 'docs').glob('*.md')]
    for n in re.findall(r'\[\[([^\]|#]+)', text):
        n = re.sub(r'[\\/:*?"<>|]', '', n).strip()
        if n and n not in names and n not in skip and not (L.root / 'docs' / f'{n}.md').is_file():
            same = next((h for h in have if len(min(h, n, key=len)) >= 2 and (h.endswith(' ' + n) or n.endswith(' ' + h) or h.startswith(n + '(') or n.startswith(h + '('))), '')
            if same:                       # 'OO면'과 'OO도 OO군 OO면', '중동'과 '중동(공주)'처럼 같은 곳을 다르게 부른 링크다. 문서를 하나 더 열지 않고 있는 문서로 건다(같은 면·동 문서가 둘 생겼다)
                relink_to(L, n, same)
                continue
            names.append(n)
    return names


def relink_to(L, name, doc):
    """[[name]] 링크를 이미 있는 문서 doc 으로 돌린다. 글자는 그대로 보인다. 역사 탭의 옛 판도 같이 고친다(옛 판에 남은 링크가 검사 오류가 됐다)."""
    with LOCK:
        for p in list((L.root / 'docs').glob('*.md')) + list((L.root / 'history').glob('*/*.md')):
            t = old = p.read_text(encoding='utf-8-sig')
            t = re.sub(r'\[\[' + re.escape(name) + r'(?:\|([^\]]*))?\]\]', lambda m: f'[[{doc}|{m[1] or name}]]', t)
            if t != old:
                S.write(p, t)
    tick(L)


