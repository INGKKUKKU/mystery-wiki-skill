def tick(L):
    """편집 하나를 반영했다. 화면과 역사에 곧바로 올린다. 기다리지 않아도 편집마다 판이 하나씩 남는다."""
    show = getattr(L, 'rebuild', None)
    if show:
        show()


def split_doc(text):
    """-> (머리말 줄들, 본문, 토론부터 끝까지)"""
    meta = []
    if m := re.match(r'---\n(.*?)\n---\n', text, re.S):
        meta = m[1].splitlines(); text = text[m.end():]
    i = text.find('\n---토론---')
    j = text.find('\n---역사---') if i < 0 else i
    return (meta, text, '') if j < 0 else (meta, text[:j], text[j:])


def join_doc(meta, body, tail):
    return '---\n' + '\n'.join(meta) + '\n---\n' + body.rstrip('\n') + '\n' + tail


def set_meta(meta, key, value):
    meta[:] = [l for l in meta if not l.startswith(key + ':')] + [f'{key}: {value}']


def set_section(body, title, content, append):
    content = re.sub(r'^## .*\n', '', content.strip('\n'), count=1) if content.lstrip().startswith('## ') else content.strip('\n')
    heads = list(re.finditer(r'^## (.+?)[ \t]*$', body, re.M))
    norm = lambda t: re.sub(r'[\s의과와및]', '', t)
    import difflib
    same = next((h[1].strip() for h in heads if h[1].strip() == title), None) or next((h[1].strip() for h in heads if norm(h[1]) == norm(title) or difflib.SequenceMatcher(None, norm(h[1]), norm(title)).ratio() >= 0.7), None)
    title = same or title          # 거의 같은 제목(귀환 뒤 생활 / 귀환 이후의 생활)은 있던 문단에 넣는다
    for k, h in enumerate(heads):
        if h[1].strip() == title:
            end = heads[k + 1].start() if k + 1 < len(heads) else len(body)
            old = body[h.end():end].strip('\n')
            if append and content.strip() and content.strip() in old:
                return body
            new = (old + '\n\n' + content) if append and old else content
            return body[:h.end()] + '\n' + new + '\n\n' + body[end:]
    block = f'## {title}\n{content}\n\n'
    rank = ORDER.index(title) if title in ORDER else len(ORDER)
    for h in heads:                                   # 정해진 문단 순서에서 뒤에 오는 첫 문단 앞에 끼운다
        if h[1].strip() in ORDER and ORDER.index(h[1].strip()) > rank:
            return body[:h.start()] + block + body[h.start():]
    return body.rstrip('\n') + '\n\n' + block


def guarded(L, name, case):
    """그 문서에 다른 사건들이 둔 단서 문장의 열쇠말(조각 표의 문구). 공유 문서를 고쳐 써도 이것은 남아야 한다."""
    out = []
    for f in (L.root / 'plan').glob('*/pieces.md'):
        if f.parent.name == case:
            continue
        for l in read(f).splitlines():
            c = [x.strip() for x in l.strip().strip('|').split('|')]
            if l.strip().startswith('|') and len(c) >= 7 and c[4] == name and c[6] and c[0] != '번호':
                out.append(c[6])
    return out


NICK_LOCK = threading.Lock()


def nick_root(n):
    """닉네임의 뿌리: 앞뒤의 숫자와 밑줄·점을 떼고 소문자로. june_84 와 june85 는 뿌리가 같다."""
    return re.sub(r'^[\d_.\-]+|[\d_.\-]+$', '', n.strip().lower())


def regular(L, n):
    """이미 이 위키에 있는 편집자와 뿌리만 같고 숫자만 다른 닉네임은 그 편집자로 합친다. 모델은 몇 안 되는 뿌리에 숫자만 바꿔
    여러 사람을 만들었다(2026-11-22, 닉네임 93개 중 아홉 묶음: june_82·83·84·85, hyeon_82·83·84·92 …). 합치면 실제 위키처럼 단골이 생긴다.
    이름을 새로 짓지는 않는다. 뿌리가 너무 짧으면(영문 셋, 한글 둘 미만) 합치지 않는다."""
    n = (n or '').strip()
    if not n:
        return n
    with NICK_LOCK:                   # apply 가 LOCK 을 쥔 채로 부른다. 같은 LOCK 을 쓰면 멈춘다
        if getattr(L, '_nicks', None) is None:          # 처음 한 번: 편집 기록과 토론에서 이미 쓰인 닉네임을 모은다
            known = {}
            revs = json.loads(read(L.root / 'history' / 'revs.json') or '{}')
            seen = [r.get('editor', '') for rows in revs.values() for r in rows]
            for p in (L.root / 'docs').glob('*.md'):
                seen += re.findall(r'\*\*([^*\n]{1,30})\*\* \(\d{4}-', read(p))
            for s in seen:
                known.setdefault(nick_root(s), s.strip())
            L._nicks = known
        root = nick_root(n)
        short = len(root) < (2 if re.search(r'[가-힣]', root) else 3)
        if short or root not in L._nicks:
            if not short:
                L._nicks[root] = n
            return n
        return L._nicks[root]


WIN_RESERVED = {'CON', 'PRN', 'AUX', 'NUL', *(f'COM{i}' for i in range(1, 10)), *(f'LPT{i}' for i in range(1, 10))}


def apply(L, text, case=None, safe=False, kinds=('사건', '지역', '기관', '매체', '장소', '인물', '기타'), history=False):
    """편집 지시문을 하나씩 반영한다. -> (반영한 편집 수, 사건 폴더 이름)"""
    blocks = re.split(r'^=== ', '\n' + text.replace('\r\n', '\n'), flags=re.M)[1:]
    n = 0
    for b in blocks:
        head, _, rest = b.partition('\n'); h = [x.strip() for x in head.split('|')]
        if h[0] == '사건' and len(h) > 1:
            case = re.sub(r'[\\/:*?"<>|\s]', '', h[1])[:20] or '사건'; (L.root / 'plan' / case).mkdir(parents=True, exist_ok=True)
        elif h[0] not in ('문서', '세계') and len(h) > 1 and case and re.fullmatch(r'[\w.-]+\.md', re.split(r'[\\/]', h[1])[-1]):
            # 머리말 낱말을 다르게 쓰거나 파일 이름 앞에 폴더를 붙여 와도 설계 파일로 받는다. 형식 하나 때문에 호출 하나를 통째로 버리지 않는다
            if re.split(r'[\\/]', h[1])[-1] == 'truth.md' and json.loads(read(L.root / 'plan' / case / 'state.json') or '{}').get('sealed'):
                continue                 # 봉한 진상은 고치지 못한다
            S.write((L.root / 'plan' / case / re.split(r'[\\/]', h[1])[-1]), rest.strip('\n') + '\n')
        elif h[0] == '세계':
            row = rest.strip().splitlines()[0].strip() if rest.strip() else (h[1] if len(h) > 1 else '')
            if row.startswith('|'):
                with LOCK:
                    p = L.root / 'plan' / 'truth.md'; S.write(p, read(p).rstrip('\n') + '\n' + row + '\n')
        elif h[0] == '문서' and len(h) > 1:
            name = re.sub(r'[\\/:*?"<>|]', '', h[1]).strip()
            if name.startswith('.') or name.split('.')[0].upper() in WIN_RESERVED:      # 숨은 파일이나 윈도우가 못 여는 이름으로 문서를 만들지 않는다
                continue
            m = re.match(r'--- ?(새문서|문단|덧붙임|토론|고침)[ \t]*(?:\|[ \t]*(.*?))?[ \t]*\n', rest.lstrip('\n'))
            if not name or name == '대문' or not m:
                continue
            op, title, content = m[1], (m[2] or '').strip(), rest.lstrip('\n')[m.end():]
            content = re.split(r'^--- ?(?:새문서|문단|덧붙임|토론|고침)', content, flags=re.M)[0].strip('\n')
            content = re.sub(r'^(#{2,4}[ \t]+)\d+(?:\.\d+)*[.)][ \t]+', r'\1', content, flags=re.M)      # 제목 앞의 번호는 목차가 붙인다
            path = L.root / 'docs' / f'{name}.md'
            kind = (re.search(r'^type:[ \t]*(\S+)', content, re.M) or ['', ''])[1] if op == '새문서' else ''
            if not path.is_file() and (op != '새문서' or kind not in kinds):      # 머리말에 문서 종류가 없는 것은 문서가 아니다
                continue
            if op == '새문서' and path.is_file():      # 이미 있는 문서를 다시 열라는 편집은 버린다. 같은 내용이 두 번 쌓인다
                continue
            with LOCK:
                if op == '새문서' or not path.is_file():
                    if op == '새문서':
                        meta, body, tail = split_doc(content + '\n')
                    else:
                        meta, body, tail = ['type: 기타'], '', ''
                    if path.is_file():                 # 이미 있으면 덮어쓰지 않고 본문만 덧붙인다
                        meta, old, tail = split_doc(path.read_text(encoding='utf-8-sig').replace('\r\n', '\n')); body = old.rstrip('\n') + '\n\n' + body
                else:
                    meta, body, tail = split_doc(path.read_text(encoding='utf-8-sig').replace('\r\n', '\n'))
                before = body if path.is_file() else ''
                if op == '고침':
                    if not path.is_file():
                        continue
                    for old, new in re.findall(r'^<<<[ \t]*\n(.*?)\n>>>[ \t]*\n?(.*?)(?=\n<<<|\Z)', content, re.S | re.M):
                        old, new = old.strip(), new.strip()
                        if not old:
                            continue
                        if old in body:
                            body = body.replace(old, new, 1)
                        elif old in '\n'.join(meta):     # 머리말도 고칠 수 있어야 한다. 검사가 머리말(search: true)을 요구했는데 고침이 본문만 봐서 사건이 멈췄다
                            meta = [l for l in '\n'.join(meta).replace(old, new, 1).split('\n') if l.strip()]
                        for hp in [] if not history else (L.root / 'history' / name.replace(' ', '_')).glob('*.md'):
                            t = hp.read_text(encoding='utf-8')
                            if old in t:
                                S.write(hp, t.replace(old, new))
                    body = re.sub(r'[ \t]{2,}', ' ', body); body = re.sub(r'\n{3,}', '\n\n', body)
                elif op in ('문단', '덧붙임') and title:
                    keep = op == '문단' and safe and set(re.findall(r'\[\[[^\]]+\]\]', section(body, title))) <= set(re.findall(r'\[\[[^\]]+\]\]', content))
                    body = set_section(body, title, content, op == '덧붙임' or (safe and not keep))      # 다른 문서의 문단은 원래 있던 링크를 다 지킬 때만 바꿔 쓴다
                elif op == '토론':
                    k = tail.find('\n---역사---'); talk, hist = (tail, '') if k < 0 else (tail[:k], tail[k:])
                    content = re.sub(r'\*\*([^*\n]{1,30})\*\*(?= \()', lambda m: f'**{regular(L, m[1])}**', content)
                    tail = (talk if talk.strip() else '\n---토론---') .rstrip('\n') + '\n' + content + '\n' + hist
                if [q for q in guarded(L, name, case) if q in before and q not in body]:
                    continue             # 다른 사건의 단서 문장을 지우는 편집은 반영하지 않는다
                set_meta(meta, 'edit', f'{regular(L, h[2]) if len(h) > 2 and h[2] else "익명"} | {h[3] if len(h) > 3 else ""}')
                S.write(path, join_doc(meta, body, tail)); n += 1
                tick(L)
    return n, case


