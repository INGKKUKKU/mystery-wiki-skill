def tidy(L):
    """사람 소개를 `성 모 씨(당시 N세)` 한 꼴로 맞추고, 문서마다 개요에서 한 번 본문에서 한 번만 남긴다.
    여럿이 나눠 쓰면 저마다 처음 소개하듯 쓰고, 나이 적는 꼴도 제각각이 되기 때문이다."""
    intro = re.compile(r'([가-힣]) (?:모 )?씨\((?:당시 )?(\d+)세?\)')
    for p in (L.root / 'docs').glob('*.md'):
        if p.stem == '대문':
            continue
        with LOCK:
            meta, body, tail = split_doc(read(p).replace('\r\n', '\n'))
            m = re.search(r'^## 개요[ \t]*\n.*?(?=^## |\Z)', body, re.M | re.S)
            cut = m.end() if m else 0

            def part(text):
                seen = set()

                def once(mm):
                    if mm[1] in seen:
                        return f'{mm[1]} 씨'
                    seen.add(mm[1]); return f'{mm[1]} 모 씨(당시 {mm[2]}세)'
                return intro.sub(once, text)
            case_doc = any(l.split(':', 1)[1].strip() == '사건' for l in meta if l.startswith('type:'))      # 인물·장소 문서는 지금 시점에서 쓴다. '당시'를 붙이지 않는다
            new = relink(part(body[:cut]) + part(body[cut:]) if case_doc else body, p.stem)
            if new != body:
                set_meta(meta, 'edit', '문서규정 | 표기와 링크 정리')
                S.write(p, join_doc(meta, new, tail)); tick(L)


