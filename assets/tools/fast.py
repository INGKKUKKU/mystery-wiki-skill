def place_images(L, case, last=False):
    """사진 주문서의 사진마다 문서에 자리를 넣는다. 사진 파일은 뒤에서 따로 만들어져 생기는 대로 뜬다.
    놓을 문단이 아직 안 쓰였으면 건너뛰고(다음에 부를 때 놓는다), last 일 때만 첫 문단으로 돌린다.
    문단 안에서는 그 사진이 찍은 것을 말하는 대목 바로 아래에 놓는다."""
    for line in read(L.root / 'plan' / case / 'images.md').splitlines():
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        path = L.root / 'docs' / f'{c[1]}.md' if len(c) > 5 else None
        if not path or not line.strip().startswith('|') or not re.fullmatch(r'[\w.-]+\.(png|jpg|jpeg|webp)', c[0]) or not path.is_file():
            continue
        with LOCK:
            meta, body, tail = split_doc(path.read_text(encoding='utf-8-sig').replace('\r\n', '\n'))
            if f']({c[0]})' in body:
                continue
            m = re.search(r'^## ' + re.escape(c[4]) + r'[ \t]*\n.*?(?=^## |\Z)', body, re.M | re.S)
            if not m:
                m = re.search(r'^## (?!개요).*\n.*?(?=^## |\Z)', body, re.M | re.S) if last else None
                if not m:
                    continue
            blocks = list(re.finditer(r'[^\n].*?(?=\n\n|\Z)', m[0], re.S))
            texts = [b for b in blocks if any(l and l[0] not in '#!:|' for l in b[0].split('\n'))]      # 소제목 바로 밑에 빈 줄 없이 붙은 글도 글이다
            if not texts:
                continue
            spot = [b for b in texts if len(c) > 7 and len(c[7]) > 3 and c[7] in b[0]]      # 사진 담당이 적은 구절이 든 대목
            keys = {w[:2] for w in re.findall(r'[가-힣A-Za-z0-9]{2,}', c[5] + ' ' + c[2])}      # 구절이 고쳐져 없어졌으면 낱말이 겹치는 대목
            best = spot[0] if spot else max(texts, key=lambda b: sum(k in b[0] for k in keys))
            at = m.start() + best.end()
            set_meta(meta, 'edit', '자료보관함 | 사진 추가')
            S.write(path, join_doc(meta, body[:at] + f'\n\n![{c[5]}]({c[0]})' + body[at:], tail)); tick(L)


def relink(body, own=''):
    """링크를 그 이름이 처음 나오는 자리로 옮긴다. 정보 상자(::: 사이)에 한 번, 본문에 한 번만 남긴다.
    ponytail: 이름이 더 긴 낱말의 앞머리일 때(남강 / 남강여관)도 건다. 그런 일이 보이면 뒤 글자까지 보는 쪽으로."""
    LINK = re.compile(r'\[\[([^\]|#]+)(#[^\]|]*)?(?:\|([^\]]+))?\]\]')
    names = []
    for m in LINK.finditer(body):
        n = m[1].strip()
        if n and n != own and n not in names:
            names.append(n)
    if not names:
        return body
    segs = re.split(r'(^:::.*?^:::[ \t]*$)', body, flags=re.M | re.S)          # 홀수 칸이 정보 상자

    def first(text, word, boxed):
        """word 가 처음 나오는 자리. 제목 줄, 사진 줄, 이미 걸린 링크 안, 다른 낱말의 가운데는 건너뛴다."""
        spans = [(m.start(), m.end()) for m in LINK.finditer(text)]
        for m in re.finditer(re.escape(word), text):
            a = m.start(); line = text[text.rfind('\n', 0, a) + 1:a]
            if any(x <= a < y for x, y in spans) or (a and re.match(r'[가-힣A-Za-z0-9]', text[a - 1])):
                continue
            if boxed and '|' not in line:          # 정보 상자에서는 값 칸에만 건다(첫 줄은 제목이다)
                continue
            if not boxed and re.match(r'[ \t]*(#|!\[|:::)', line + word):
                continue
            return a
        return -1
    for n in sorted(names, key=len, reverse=True):
        for boxed in (True, False):
            idx = [i for i in range(len(segs)) if (i % 2 == 1) == boxed]
            label = ''
            for i in idx:                      # 걸려 있던 것을 다 풀고(보이던 글자는 그대로), 처음 자리에 다시 건다
                def undo(m):
                    nonlocal label
                    if m[1].strip() != n:
                        return m[0]
                    label = label or (m[3] or '')
                    return m[3] or m[1]
                segs[i] = LINK.sub(undo, segs[i])
            for word, form in ((n, f'[[{n}]]'), (label, f'[[{n}|{label}]]')):
                hit = next(((i, a) for i in idx for a in [first(segs[i], word, boxed)] if a >= 0), None) if word and not (boxed and word != n) else None
                if hit:
                    i, a = hit; segs[i] = segs[i][:a] + form + segs[i][a + len(word):]; break
    return ''.join(segs)


