def used(L, short=False):
    """지금까지 쓴 사건의 이름표. 사건마다 한 줄이다(무엇을 모르는 사건이었나, 언제 어디의 일이었나).
    알고 보니 어떤 일이었나도 한 줄 붙는다. 이것이 없으면 겉은 달라도 속사정이 같은 사건이 되풀이된다(얼개 스무 개씩 재어 봄).
    그보다 자세히 적으면 그것이 본보기가 되어 다음 사건을 끌어당긴다."""
    groups, seen = [], set()          # 앞 묶음은 이 위키의 것, 뒤 묶음은 위키를 새로 파도 남는 것. 사건 이름이 같으면 앞의 것만 둔다
    for p in used_files(L):
        labels = []; name, about = '', ''
        for l in read(p).splitlines() + ['### ']:
            if l.startswith('### '):                         # 옛 꼴: 사건마다 여러 줄. 모르는 것(없으면 구도) 한 줄만 쓴다
                if name and about and name not in seen:
                    labels.append(f'- {name}: {about}'); seen.add(name)
                name, about = l[4:].strip(), ''
            elif l.startswith('- 모르는 것:') or (l.startswith('- 구도:') and not about):
                about = l.split(':', 1)[1].strip()
            elif l.startswith('* ') and l[2:].split(':', 1)[0].strip() not in seen:      # 새 꼴: 한 줄
                labels.append(l.split(' → ')[0].split(' / ')[0]); seen.add(l[2:].split(':', 1)[0].strip())      # 옛 줄의 풀이와 수수께끼는 떼고 보인다. 추상적인 풀이 문장이 다음 사건의 본보기가 됐다
        groups.append(labels)
    here, rest = groups[0], sum(groups[1:], [])
    if short:          # 얼개용: 알고 보니와 때만. 훅까지 붙이니 얼개가 두 배 넘게 길어졌고(100~140초 → 170~1,080초, 2026-11-23 루프) 겉의 반복도 줄지 않았다. 이름표 전체를 주고 공통점을 찾게 하면 사건이 쌓일수록 얼개가 길어졌다(13건에 추론 9,500토큰, 8분. 2026-11-22 재현 15회)
        def cut(l):
            when = re.search(r'\(([^()]*)\)\s*(?:\||$)', l)
            gist_ = l.split(' | 알고 보니:')[1].strip() if ' | 알고 보니:' in l else l.split(':', 1)[-1].split(' [')[0].strip()
            return l.split(':', 1)[0] + ': ' + gist_ + (f' ({when.group(1).strip()})' if when else '')      # 때와 곳은 자르지 않는다. 첫 쉼표에서 자르니 '1983년 이산가족 찾기'가 잘려 나가 같은 역사 배경이 되풀이됐다
        here = [cut(l) for l in here]
    return '\n'.join(here[-40:]) or '(아직 없음)'


