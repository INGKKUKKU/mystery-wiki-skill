def align_pieces(L, case):
    """조각 표의 문구가 문서 문장을 조금 바꿔 옮겨 적혀 마감 검사에 걸리면, 그 문서에서 가장 비슷한 실제 문장으로 바꾼다.
    조각 표는 문서의 문장을 그대로 옮기는 표다. 고치는 호출은 문서 쪽을 손대려다 끝났다(2026-11-20). 바꾼 칸 수를 돌려준다."""
    import difflib
    path = L.root / 'plan' / case / 'pieces.md'; text = read(path); n = 0
    flat = lambda t: re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1', t).replace('**', '').replace('~~', '')
    rows = text.split('\n'); head = [c.strip() for c in rows[0].strip().strip('|').split('|')] if rows else []
    if '문서' not in head or '문구' not in head:
        return 0
    di, qi = head.index('문서'), head.index('문구')
    ci = head.index('내용') if '내용' in head else None
    for k, row in enumerate(rows[2:], 2):
        cells = row.strip().strip('|').split('|')
        if len(cells) <= max(di, qi):
            continue
        doc, quote = cells[di].strip(), cells[qi].strip()
        body = flat(split_doc(read(L.root / 'docs' / f'{doc}.md'))[1])
        if not quote or not body or quote in body:
            continue
        # 후보: 문장, 쉼표로 나뉜 절(문서가 두 사실을 한 문장에 합친 경우), 이어진 두 문장(한 사실을 둘로 나눈 경우). 모두 본문에 그대로 있는 글자다
        spans = [m.span() for m in re.finditer(r'[^.?!\n]+[.?!]?', body)]
        sents = [body[a:b].strip() for a, b in spans]
        base = [x for x in sents if len(x) > 8 and '|' not in x and not x.startswith('#')]      # 낱문장. 내용으로 찾을 때는 이것만 견준다(이은 문장이 같은 점수로 겹쳐 1등을 못 가렸다)
        sents += [c.strip() for s in sents for c in s.split(', ')]
        sents += [body[spans[i][0]:spans[i + 1][1]].strip() for i in range(len(spans) - 1) if '\n' not in body[spans[i][0]:spans[i + 1][1]]]
        sents = [s for s in sents if len(s) > 8 and '|' not in s and s in body]
        best = max(sents, key=lambda s: difflib.SequenceMatcher(None, quote, s).ratio(), default='')
        if not (best and difflib.SequenceMatcher(None, quote, best).ratio() >= 0.55):
            # 표에 든 사실을 기록 담당이 문장으로 풀어 적으면 닮은 문장이 없다(2026-11-22, 참가금·지급액 표). 그때는 조각 문구와
            # 본문이 글자 그대로 겹치는 가장 긴 구절로 맞춘다(길이가 같으면 숫자가 든 것). 표 칸은 넘지 않는다
            pieces_ = [c.strip() for line in body.split('\n') for c in line.split('|') if c.strip()]
            runs = []
            for c in pieces_:
                m = difflib.SequenceMatcher(None, quote, c, autojunk=False).find_longest_match(0, len(quote), 0, len(c))
                run = c[m.b:m.b + m.size].strip(' ,.')
                if len(run) >= 6 and run in body:
                    runs.append(run)
            best = max(runs, key=lambda r: (len(r), any(ch.isdigit() for ch in r)), default='')
        if not best and ci is not None and len(cells) > ci:
            # 문구가 진상 쪽 표현(가린 실명, 메모 원문)이라 문서와 겹치는 글자가 거의 없을 때(2026-11-22, 파업 사건 두 줄로 사건이 미완성으로 멈춤).
            # 그 줄의 '내용'은 같은 사실을 풀어 쓴 것이라, 글자 두 개씩 겹치는 정도로 문서의 문장을 찾는다. 뚜렷이 앞서는 문장일 때만 맞춘다
            grams = lambda t: {t[i:i + 2] for i in range(len(t) - 1) if ' ' not in t[i:i + 2]}
            want = grams(flat(cells[ci].strip()))
            ranked = sorted(((len(want & grams(s)) / len(want), s) for s in base), reverse=True) if want else []
            if ranked and ranked[0][0] >= 0.45 and (len(ranked) == 1 or ranked[0][0] - ranked[1][0] >= 0.1):
                best = ranked[0][1]
        if best:
            cells[qi] = f' {best} '; rows[k] = '|' + '|'.join(cells) + '|'; n += 1
    if n:
        S.write(path, '\n'.join(rows))
    return n


